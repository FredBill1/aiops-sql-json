import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { documentationPageUrls, extractDocumentationContracts } from './function-catalog-extractors.mjs';

const workspace = process.cwd();
const sourcesPath = path.join(workspace, 'catalog', 'function-catalog.sources.json');
const lockPath = path.join(workspace, 'catalog', 'function-catalog.lock.json');
const outputPath = path.join(workspace, 'src', 'generated', 'sqlFunctionNames.ts');
const sources = JSON.parse(await readFile(sourcesPath, 'utf8'));
const coverage = JSON.parse(await readFile(path.join(workspace, 'catalog', 'function-catalog.coverage.json'), 'utf8'));
const generated = {};
const contracts = {};
const lock = {};
const cacheDirectory = path.join(workspace, 'coverage', 'function-catalog-pages');
await mkdir(cacheDirectory, { recursive: true });

for (const [dialect, source] of Object.entries(sources)) {
  const pages = await downloadDocumentation(dialect, source);
  const html = pages.map((page) => page.html).join('\n');
  const checksum = createHash('sha256').update(html).digest('hex');
  // Detail pages also mention JSON-path methods, connector-only functions, type
  // constructors and examples. They enrich contracts, not the callable-name
  // index. PostgreSQL's index is a chapter TOC, as in the original extractor.
  const nameHtml = source.extractor === 'postgresql' ? html : pages.find((page) => page.url === source.url).html;
  const names = extractNames(source.extractor, nameHtml);
  if (names.length < 20) {
    throw new Error(`${dialect}: extracted only ${names.length} functions; the upstream page format probably changed`);
  }
  if (names.length > 0) generated[dialect] = names;
  const extracted = extractDocumentationContracts(dialect, pages);
  contracts[dialect] = Object.fromEntries(names.filter((name) => extracted[name]).map((name) => [name, extracted[name]]));
  const counts = { complete: 0, partial: 0, 'name-only': names.length - Object.keys(contracts[dialect]).length };
  for (const contract of Object.values(contracts[dialect])) counts[contract.completeness]++;
  if (counts.complete + counts.partial < coverage[dialect].minimumDocumentedReturns) {
    throw new Error(`${dialect}: return-contract extraction regressed; generated files have not been replaced`);
  }
  lock[dialect] = {
    version: source.version,
    url: source.url,
    sha256: checksum,
    extraction: source.extractor,
    extractedFunctions: names.length,
    pages: pages.map((page) => ({ url: page.url, sha256: createHash('sha256').update(page.html).digest('hex') })),
    contracts: counts,
  };
  console.log(`${dialect}: ${names.length} names; ${counts.complete} complete, ${counts.partial} partial, ${counts['name-only']} name-only contracts`);
}

const generatedSource = `import type { SqlDialect } from '../sql';

/** Generated by \`npm run catalog:update\`; do not edit by hand. */
export const GENERATED_FUNCTION_NAMES: Partial<Record<SqlDialect, readonly string[]>> = ${JSON.stringify(generated, null, 2)};
`;

await writeFile(outputPath, generatedSource, 'utf8');
const generatedContracts = `import type { SqlDialect } from '../sql';
import type { DocumentedFunctionContract } from '../sqlFunctionCatalogTypes';

/** Generated by \`npm run catalog:update\`; do not edit by hand. */
export const GENERATED_FUNCTION_CONTRACTS: Partial<Record<SqlDialect, Readonly<Record<string, DocumentedFunctionContract>>>> = ${JSON.stringify(contracts, null, 2)};
`;
await writeFile(path.join(workspace, 'src', 'generated', 'sqlFunctionContracts.ts'), generatedContracts, 'utf8');
for (const dialect of Object.keys(lock)) {
  lock[dialect].contractsSha256 = createHash('sha256').update(JSON.stringify(contracts[dialect])).digest('hex');
}
await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`, 'utf8');
console.log(`Updated ${Object.values(generated).reduce((count, names) => count + names.length, 0)} generated function names.`);

function extractNames(extractor, html) {
  const names = new Set();
  if (extractor === 'spark') {
    for (const match of html.matchAll(/<td>\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(/gu)) names.add(match[1].toUpperCase());
    for (const syntaxName of [
      'BIGINT', 'BINARY', 'BITWISE', 'BOOLEAN', 'CAST', 'DATE', 'DECIMAL', 'DOUBLE', 'FLOAT',
      'INT', 'MEASURE', 'SMALLINT', 'STRING', 'TIME', 'TIMESTAMP', 'TINYINT',
    ]) names.delete(syntaxName);
  } else if (extractor === 'trino') {
    for (const match of html.matchAll(/<span class="pre">([A-Za-z_][A-Za-z0-9_]*)\(\)<\/span>/gu)) {
      names.add(match[1].toUpperCase());
    }
    for (const connectorFunction of ['RANDOM_STRING']) names.delete(connectorFunction);
  } else if (extractor === 'mysql') {
    for (const row of html.matchAll(/<tr>([\s\S]*?)<\/tr>/gu)) {
      if (/internal-functions|gatekeeper-functions|loadable-function/iu.test(row[1])) continue;
      const match = /<code class="literal">([A-Za-z_][A-Za-z0-9_]*)\(\)<\/code>/u.exec(row[1]);
      if (match) names.add(match[1].toUpperCase());
    }
    for (const syntaxName of ['EXISTS']) names.delete(syntaxName);
  } else if (extractor === 'hive') {
    for (const cell of html.matchAll(/<td[^>]*>([\s\S]*?)<\/td>/giu)) {
      const text = htmlText(cell[1]);
      const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(/u.exec(text);
      if (match) names.add(match[1].toUpperCase());
    }
    for (const tableFunction of ['EXPLODE', 'POSEXPLODE', 'JSON_TUPLE', 'PARSE_URL_TUPLE']) {
      names.add(tableFunction);
    }
  } else if (extractor === 'flink') {
    for (const match of html.matchAll(/<td[^>]*>\s*([A-Z][A-Z0-9_]*)\s*\(/gu)) names.add(match[1]);
  } else if (extractor === 'postgresql') {
    for (const match of html.matchAll(/<code class="function">\s*([A-Za-z_][A-Za-z0-9_]*)\s*<\/code>\s*\(/gu)) {
      names.add(match[1].toUpperCase());
    }
  } else if (extractor === 'impala') {
    for (const match of html.matchAll(/<a class="xref"[^>]*>\s*([A-Z][A-Z0-9_]*)\s*<\/a>/gu)) {
      names.add(match[1]);
    }
  } else {
    throw new Error(`Unknown extractor ${extractor}`);
  }
  for (const nonCallableName of ['BRACKET_OP', 'IN']) names.delete(nonCallableName);
  return [...names].sort((left, right) => left.localeCompare(right));
}

async function downloadDocumentation(dialect, source) {
  const html = await download(source.url, dialect);
  const urls = documentationPageUrls(source, html);
  const pages = [];
  for (let offset = 0; offset < urls.length; offset += 6) {
    pages.push(...await Promise.all(urls.slice(offset, offset + 6).map(async (url) => ({
      url, html: url === source.url ? html : await download(url, dialect),
    }))));
  }
  return pages;
}

async function download(url, dialect) {
  const cachePath = path.join(cacheDirectory, `${createHash('sha256').update(url).digest('hex')}.html`);
  if (process.argv.includes('--offline')) return readFile(cachePath, 'utf8');
  const response = await fetch(url, {
    headers: { 'user-agent': 'aiops-sql-json-catalog-updater' }, signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`${dialect}: ${response.status} while downloading ${url}`);
  const html = await response.text();
  await writeFile(cachePath, html, 'utf8');
  return html;
}

function htmlText(value) {
  return value
    .replace(/<[^>]+>/gu, ' ')
    .replace(/&(?:hellip|#8230);/gu, '...')
    .replace(/&(?:lt|#60);/gu, '<')
    .replace(/&(?:gt|#62);/gu, '>')
    .replace(/&(?:amp|#38);/gu, '&')
    .replace(/&nbsp;/gu, ' ');
}
